import axios from 'axios';

const api = axios.create({
  baseURL: '/api',
  headers: {
    'Content-Type': 'application/json',
  },
});

// Attach JWT token from sessionStorage (or localStorage) to every outgoing request
api.interceptors.request.use(
  (config) => {
    const token = sessionStorage.getItem('fleet_token') || localStorage.getItem('fleet_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Centralized response handling: redirect on 401 expired session
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      const url = error.config?.url || '';
      if (!url.includes('/auth/login') && !url.includes('/auth/register')) {
        sessionStorage.removeItem('fleet_token');
        sessionStorage.removeItem('fleet_user');
        localStorage.removeItem('fleet_token');
        localStorage.removeItem('fleet_user');
        if (!window.location.pathname.includes('/login')) {
          window.location.href = '/login?expired=true';
        }
      }
    }
    return Promise.reject(error);
  }
);

export default api;
